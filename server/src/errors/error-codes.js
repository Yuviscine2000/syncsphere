/**
 * @param {string} code
 * @returns {number}
 */
export function getHttpStatusForErrorCode(code) {
  return ERROR_HTTP_STATUS[code] ?? 500;
}

/**
 * @param {string} code
 * @returns {string}
 */
export function getDefaultErrorMessage(code) {
  return ERROR_MESSAGES[code] ?? ERROR_MESSAGES[ERROR_CODES.INTERNAL_SERVER_ERROR];
}
